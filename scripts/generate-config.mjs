import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const PRODUCTION_AI_URL = 'https://mini-rag-alpha.vercel.app/api/v1/nlp';

export function validateUrl(urlStr) {
  if (!urlStr || typeof urlStr !== 'string') {
    return { valid: false, reason: 'URL must be a non-empty string' };
  }
  const trimmed = urlStr.trim().replace(/\/+$/, '');
  try {
    const parsed = new URL(trimmed);
    const isHttps = parsed.protocol === 'https:';
    const isLocalHttp = parsed.protocol === 'http:' && (parsed.hostname === 'localhost' || parsed.hostname === '127.0.0.1');
    if (!isHttps && !isLocalHttp) {
      return { valid: false, reason: `Protocol must be https: (got ${parsed.protocol})` };
    }
    const pathname = parsed.pathname.replace(/\/+$/, '');
    if (!pathname.endsWith('/api/v1/nlp')) {
      return { valid: false, reason: `Path must end with /api/v1/nlp (got ${parsed.pathname})` };
    }
    return { valid: true, normalized: trimmed };
  } catch (err) {
    return { valid: false, reason: `Malformed URL: ${err.message}` };
  }
}

export function computeConfig(env = process.env) {
  const vercelEnv = (env.VERCEL_ENV || 'development').trim().toLowerCase();

  let targetEnv = vercelEnv;
  let aiBaseUrl = '';

  if (vercelEnv === 'preview') {
    targetEnv = 'preview';
    const rawPreviewUrl = env.NILEGUIDE_AI_BASE_URL;
    if (!rawPreviewUrl || !rawPreviewUrl.trim()) {
      throw new Error(
        '[NileGuide Build Error] VERCEL_ENV is "preview" but NILEGUIDE_AI_BASE_URL is missing or empty. ' +
        'Preview builds must configure a dedicated preview backend URL and cannot fall back to Production.'
      );
    }
    const val = validateUrl(rawPreviewUrl);
    if (!val.valid) {
      throw new Error(`[NileGuide Build Error] Invalid NILEGUIDE_AI_BASE_URL for Preview build: ${val.reason}`);
    }
    if (val.normalized.includes('mini-rag-alpha.vercel.app')) {
      throw new Error(
        '[NileGuide Build Error] Preview builds cannot point to the Production AI backend (mini-rag-alpha.vercel.app).'
      );
    }
    aiBaseUrl = val.normalized;
  } else if (vercelEnv === 'production') {
    targetEnv = 'production';
    const rawEnvUrl = env.NILEGUIDE_AI_BASE_URL;
    if (rawEnvUrl && (rawEnvUrl.includes('mini-cyujr9ept') || rawEnvUrl.includes('-git-'))) {
      throw new Error(
        '[NileGuide Build Error] Production build rejected: NILEGUIDE_AI_BASE_URL contains a Preview URL.'
      );
    }
    aiBaseUrl = PRODUCTION_AI_URL;
  } else {
    // Development or test
    targetEnv = 'development';
    if (env.NILEGUIDE_AI_BASE_URL) {
      const val = validateUrl(env.NILEGUIDE_AI_BASE_URL);
      if (val.valid) {
        aiBaseUrl = val.normalized;
      } else {
        aiBaseUrl = PRODUCTION_AI_URL;
      }
    } else {
      aiBaseUrl = PRODUCTION_AI_URL;
    }
  }

  const generatedScript = `// Auto-generated by scripts/generate-config.mjs during build
(function() {
  window.__NILEGUIDE_CONFIG__ = Object.freeze({
    environment: ${JSON.stringify(targetEnv)},
    aiBaseUrl: ${JSON.stringify(aiBaseUrl)},
    generatedAt: ${JSON.stringify(new Date().toISOString())}
  });
})();
`;

  return {
    environment: targetEnv,
    aiBaseUrl,
    generatedScript,
  };
}

export function writeConfigFile(outputDir, config) {
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }
  const filePath = path.join(outputDir, 'nileguide-config.js');
  fs.writeFileSync(filePath, config.generatedScript, 'utf8');
  console.log(`[NileGuide Config] Generated ${filePath} (environment: ${config.environment}, aiBaseUrl: ${config.aiBaseUrl})`);
  return filePath;
}

// CLI entry point
const isCli = process.argv[1] && (
  process.argv[1].endsWith('generate-config.mjs') ||
  process.argv[1].endsWith('generate-config.js')
);

if (isCli) {
  try {
    const config = computeConfig(process.env);
    const __dirname = path.dirname(fileURLToPath(import.meta.url));
    const publicDir = path.resolve(__dirname, '../public');
    writeConfigFile(publicDir, config);
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
}
